// ─── Chart Data ──────────────────────────────────────────────────────────────
export function getDistrictCompensationChart() {
  return Object.entries(districtData)
    .map(([name, d]) => ({
      name,
      sanctioned: d.compensationSanctioned,
      disbursed: d.compensationDisbursed,
    }))
    .sort((a, b) => b.sanctioned - a.sanctioned);
}
