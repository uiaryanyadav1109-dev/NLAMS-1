// Computed KPI totals
export function getKPITotals() {
  const states = Object.values(stateData);
  return {
    totalNotified: states.reduce((s, st) => s + st.totalNotified, 0),
    totalAcquired: states.reduce((s, st) => s + st.totalAcquired, 0),
    compensationSanctioned: states.reduce((s, st) => s + st.compensationSanctioned, 0),
    compensationDisbursed: states.reduce((s, st) => s + st.compensationDisbursed, 0),
    familiesAffected: states.reduce((s, st) => s + st.familiesAffected, 0),
    totalProjects: states.reduce((s, st) => s + st.projects, 0),
  };
}

// Top 10 states by acquisition area for the bar chart
export function getTop10StatesByArea() {
  return Object.entries(stateData)
    .map(([name, data]) => ({ name, acquired: data.totalAcquired, notified: data.totalNotified }))
    .sort((a, b) => b.acquired - a.acquired)
    .slice(0, 10);
}
